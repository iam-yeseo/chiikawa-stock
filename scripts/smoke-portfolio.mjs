import {_electron as electron} from 'playwright';
import fs from 'node:fs/promises';
import path from 'node:path';
import assert from 'node:assert/strict';
const root=process.cwd(),manifest=JSON.parse(await fs.readFile('package.json','utf8'));
const packaged=process.argv.includes('--packaged');
await fs.mkdir('qa',{recursive:true});
const profile=await fs.mkdtemp(path.resolve('qa/portfolio-profile-'));
const env={...process.env,CHII_USER_DATA:profile};delete env.ELECTRON_RUN_AS_NODE;
const options=packaged?{executablePath:path.resolve(manifest.build.directories.output,`${process.arch==='arm64'?'mac-arm64':'mac'}/${manifest.build.executableName || manifest.productName}.app/Contents/MacOS/${manifest.build.executableName || manifest.productName}`),args:['--demo-preview']}:{args:[root]};
let app;const errors=[];
try{
  app=await electron.launch({...options,env,timeout:45000});
  const deadline=Date.now()+30000;
  while(Date.now()<deadline&&!['index.html','pet.html'].every(name=>app.windows().some(page=>page.url().includes(name))))await new Promise(resolve=>setTimeout(resolve,100));
  const dashboard=app.windows().find(page=>page.url().includes('index.html'));
  const pet=app.windows().find(page=>page.url().includes('pet.html'));
  assert.ok(dashboard&&pet,'both windows ready');
  for(const page of [dashboard,pet])page.on('pageerror',e=>errors.push(e.message));
  await dashboard.waitForFunction(async()=>{const s=await window.chii.getState();return s.portfolio?.status==='ready';});
  const initial=await dashboard.evaluate(()=>window.chii.getState());
  assert.equal(initial.mode,'demo');assert.equal(initial.version,manifest.version);assert.equal(initial.credentialsConfigured,false);
  assert.equal(initial.config.autoWatchHoldings,true);
  assert.equal(initial.portfolio.holdings.items.length,2);
  assert.ok(initial.portfolio.accounts.length>=2,'selection fixture includes second account');
  assert.ok(initial.portfolio.accounts.every(a=>!('accountNo' in a)&&!('accountSeq' in a)));
  assert.ok(initial.portfolio.holdings.items.every(h=>initial.config.watchlist.some(s=>s.market===h.market&&s.symbol===h.symbol)));
  await dashboard.locator('[data-page="portfolio"]').click();
  await dashboard.locator('#portfolio-holding-rows tr').first().waitFor();
  assert.equal(await dashboard.locator('#portfolio-holding-rows tr').count(),2);
  assert.ok(await dashboard.locator('#portfolio-demo-note').isVisible());
  const summaryText=await dashboard.locator('#portfolio-summary').innerText();
  assert.ok(summaryText.includes('원')&&summaryText.includes('$'),'KRW and USD displayed separately');
  await dashboard.screenshot({path:`qa/portfolio-${manifest.version}${packaged?'-packaged':''}.png`,animations:'disabled',fullPage:true});
  const current=initial.portfolio.selectedAccountId;
  const alternate=initial.portfolio.accounts.find(a=>a.id!==current).id;
  await dashboard.locator('#portfolio-account-select').selectOption(String(alternate));
  await dashboard.waitForFunction(async id=>{const s=await window.chii.getState();return s.portfolio.selectedAccountId===id&&s.portfolio.status==='ready'&&s.portfolio.holdings.items.length===0;},alternate);
  assert.equal(await dashboard.locator('#portfolio-holding-rows tr').count(),0,'previous account rows cleared');
  await dashboard.locator('#portfolio-account-select').selectOption(String(current));
  await dashboard.waitForFunction(async()=>{const s=await window.chii.getState();return s.portfolio.status==='ready'&&s.portfolio.holdings.items.length===2;});
  await dashboard.locator('#auto-watch-holdings').uncheck();
  await dashboard.waitForFunction(async()=>!(await window.chii.getState()).config.autoWatchHoldings);
  await dashboard.locator('#auto-watch-holdings').check();
  await dashboard.waitForFunction(async()=>(await window.chii.getState()).config.autoWatchHoldings);
  await dashboard.locator('#refresh-portfolio').click();
  await dashboard.waitForFunction(async()=>(await window.chii.getState()).portfolio.status==='ready');
  await assert.rejects(dashboard.evaluate(()=>window.chii.selectAccount('bad')),/계좌/);
  await assert.rejects(dashboard.evaluate(()=>window.chii.selectAccount(999999999)),/계좌/);
  await assert.rejects(pet.evaluate(()=>window.chii.refreshPortfolio()),/허용되지/);
  await pet.evaluate(()=>{window.__portfolioBulletins=[];window.__unsubscribePortfolio=window.chii.onBulletin(e=>window.__portfolioBulletins.push(e));});
  await dashboard.evaluate(()=>window.chii.updateConfig({intervalMinutes:0.1}));
  await pet.waitForFunction(()=>window.__portfolioBulletins.length>0,{},{timeout:12000});
  const bulletin=await pet.evaluate(()=>{window.__unsubscribePortfolio();return window.__portfolioBulletins[0];});
  const owned=new Set(initial.portfolio.holdings.items.map(h=>`${h.market}:${h.symbol}`));
  assert.ok(owned.has(`${bulletin.quotes[0].market}:${bulletin.quotes[0].symbol}`),'periodic bulletin begins with held stock');
  for(const key of owned)assert.ok(bulletin.quotes.some(q=>`${q.market}:${q.symbol}`===key&&typeof q.changePercent==='number'));
  await pet.waitForFunction(()=>document.querySelector('#speech-kind')?.textContent.includes('보유종목'),{},{timeout:10000});
  assert.ok((await pet.locator('#speech-body').textContent()).includes('%'),'held stock bulletin shows percentage');
  assert.deepEqual(errors,[]);
  await fs.writeFile(`qa/portfolio-${manifest.version}${packaged?'-packaged':''}.json`,JSON.stringify({passed:true,version:manifest.version,packaged,platform:process.platform,arch:process.arch,mode:'isolated synthetic account data',checks:['masked account selection and empty account','separate KRW/USD valuations','holdings auto-watch setting','manual refresh','invalid and unauthorized IPC rejected','configured six-second periodic report includes owned quotes first','pet bulletin display','no renderer errors'],errors},null,2));
  console.log('Portfolio desktop integration passed.');
}finally{if(app)await app.close();await fs.rm(profile,{recursive:true,force:true,maxRetries:5,retryDelay:200});}
